// The merge loop of left and right into merged, with or without the leftovers (opts: comparison, leftovers).
const MAIN = (cmp) => "merged = []\ni = 0\nj = 0\nwhile i < len(left) and j < len(right):\n    if left[i] " + (cmp || "<=") + " right[j]:\n        merged.append(left[i])\n        i = i + 1\n    else:\n        merged.append(right[j])\n        j = j + 1";
const LEFTOVERS = "\nwhile i < len(left):\n    merged.append(left[i])\n    i = i + 1\nwhile j < len(right):\n    merged.append(right[j])\n    j = j + 1";
const merge = (l, r, after, o) => "left = " + l + "\nright = " + r + "\n" + MAIN(o && o.cmp) + (o && o.noLeftovers ? "" : LEFTOVERS) + (after ? "\n" + after : "");
// A bottom-up merge sort of `list` (merging runs of 1, then 2, then 4, … items), then `after`.
const bottomUp = (list, after) => "items = " + list + "\nwidth = 1\nwhile width < len(items):\n    result = []\n    start = 0\n    while start < len(items):\n" +
  "        left = items[start:start + width]\n        right = items[start + width:start + 2 * width]\n        i = 0\n        j = 0\n" +
  "        while i < len(left) and j < len(right):\n            if left[i] <= right[j]:\n                result.append(left[i])\n                i = i + 1\n" +
  "            else:\n                result.append(right[j])\n                j = j + 1\n        result = result + left[i:] + right[j:]\n        start = start + 2 * width\n" +
  "    items = result\n    width = width * 2" + (after ? "\n" + after : "");
// Merging neighbouring pairs (the first pass of a bottom-up merge sort).
const pairs = (list, after) => "items = " + list + "\nresult = []\nfor k in range(0, len(items), 2):\n    a = items[k]\n    b = items[k + 1]\n    if a <= b:\n        result = result + [a, b]\n    else:\n        result = result + [b, a]" + (after ? "\n" + after : "");

