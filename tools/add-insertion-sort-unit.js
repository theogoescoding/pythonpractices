// The insertion of items[i], at the given indentation (opts: the comparison, the shift line and the insert line).
const step = (ind, o) => {
  o = o || {};
  return ind + "key = items[i]\n" + ind + "j = i - 1\n" + ind + "while j >= 0 and items[j] " + (o.cmp || ">") + " key:\n" +
    ind + "    " + (o.shift || "items[j + 1] = items[j]") + "\n" + ind + "    j = j - 1\n" + ind + (o.insert || "items[j + 1] = key");
};
// The same insertion without keeping the item in key (INSERTION_KEY_NOT_KEPT).
